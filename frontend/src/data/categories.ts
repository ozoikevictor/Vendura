const sub = (categorySlug: string, names: string[]) =>
  names.map((name) => ({
    id: `${categorySlug}-${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    slug: name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, ""),
    name,
  }));

